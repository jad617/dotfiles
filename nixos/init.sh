#!/usr/bin/env bash
# =============================================================================
# NixOS Hyprland workstation bootstrap
#
# Prerequisites:
#   1. Fresh NixOS install — boot from ISO and run:
#        nixos-generate-config --root /mnt
#        nixos-install
#        reboot
#   2. Log in, clone dotfiles:
#        nix-shell -p git --command "git clone <repo> ~/nodestack/dotfiles"
#   3. Run this script:
#        cd ~/nodestack/dotfiles && bash nixos/init.sh
#
# What this script does:
#   - Prompts for username / hostname / timezone
#   - Copies flake.nix + configuration.nix (with substitutions) to /etc/nixos/
#   - Enables Nix flakes
#   - Creates all dotfiles symlinks (lib/link-dotfiles.sh), first: they need no network
#   - Runs nixos-rebuild switch (a failure, e.g. offline, is reported at the end;
#     the steps after it still run)
#   - Sets up TPM, neovim python, zsh default shell
# =============================================================================
set -euo pipefail

DOTFILES="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
NIXOS_DIR="$DOTFILES/nixos"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
clone_if_missing() {
    local repo=$1 dest=$2
    if [[ ! -d "$dest" ]]; then
        git clone "$repo" "$dest"
    else
        echo "  already exists: $dest"
    fi
}

cmd_exists() { command -v "$1" &>/dev/null; }

header() { echo; echo "==> $*"; }

# ---------------------------------------------------------------------------
# Guard — must be on NixOS
# ---------------------------------------------------------------------------
if ! grep -q 'ID=nixos' /etc/os-release 2>/dev/null; then
    echo "ERROR: This script is for NixOS only."
    echo "       For Pop!_OS / macOS run the root init.sh instead."
    exit 1
fi

# ---------------------------------------------------------------------------
# Configuration — auto-detect where possible, cache timezone
# ---------------------------------------------------------------------------
header "Gathering configuration"

USERNAME="$(whoami)"
HOSTNAME="$(hostname)"

# Cache timezone so re-runs don't prompt again
TZ_CACHE="$DOTFILES/.nixos_timezone"
if [[ -n "${NIXOS_TIMEZONE:-}" ]]; then
    TIMEZONE="$NIXOS_TIMEZONE"
elif [[ -f "$TZ_CACHE" ]]; then
    TIMEZONE="$(cat "$TZ_CACHE")"
    echo "  Timezone : $TIMEZONE (cached — delete .nixos_timezone to change)"
else
    read -rp "  Timezone [America/Toronto]: " INPUT_TZ
    TIMEZONE="${INPUT_TZ:-America/Toronto}"
    echo "$TIMEZONE" > "$TZ_CACHE"
fi

echo "  Username : $USERNAME"
echo "  Hostname : $HOSTNAME"
echo "  Timezone : $TIMEZONE"

# Flake host: NIXOS_HOST, else the one named like this machine, else the
# UTM VM on an arm64 Mac (nixos-arm)
if [[ -n "${NIXOS_HOST:-}" ]]; then
    FLAKE_HOST="$NIXOS_HOST"
elif [[ -f "$NIXOS_DIR/hosts/$HOSTNAME.nix" ]]; then
    FLAKE_HOST="$HOSTNAME"
elif [[ "$(uname -m)" == aarch64 ]]; then
    FLAKE_HOST="nixos-arm"
else
    echo "ERROR: no flake host for '$HOSTNAME' (hosts: $(sed -n 's/^ *\([A-Za-z0-9_-]*\) *= *mkHost .*/\1/p' "$NIXOS_DIR/flake.nix" | xargs))."
    echo "       Add nixos/hosts/$HOSTNAME.nix + an entry in nixos/flake.nix, or run: NIXOS_HOST=<host> $0"
    exit 1
fi
echo "  Host     : $FLAKE_HOST"

# ---------------------------------------------------------------------------
# Flakes are enabled via configuration.nix (nix.settings.experimental-features)
# — no need to touch /etc/nix/nix.conf (read-only on NixOS)
# ---------------------------------------------------------------------------

# ---------------------------------------------------------------------------
# Copy NixOS config to /etc/nixos/
# ---------------------------------------------------------------------------
header "Setting up /etc/nixos"

# Preserve hardware-configuration.nix generated by nixos-generate-config
if [[ ! -f /etc/nixos/hardware-configuration.nix ]]; then
    echo "ERROR: /etc/nixos/hardware-configuration.nix not found."
    echo "       Run: sudo nixos-generate-config"
    exit 1
fi

echo "  Copying flake.nix + hosts/"
sudo cp "$NIXOS_DIR/flake.nix" /etc/nixos/flake.nix
sudo rm -rf /etc/nixos/hosts
sudo cp -r "$NIXOS_DIR/hosts" /etc/nixos/hosts
sudo cp "$NIXOS_DIR/gpu.nix" /etc/nixos/gpu.nix
# GPU drivers: gpu.nix reads the detected cards from gpu.json
bash "$NIXOS_DIR/lib/detect-gpu.sh" | sudo tee /etc/nixos/gpu.json >/dev/null
echo "  GPU      : $(cat /etc/nixos/gpu.json)"
[[ -f "$NIXOS_DIR/flake.lock" ]] && sudo cp "$NIXOS_DIR/flake.lock" /etc/nixos/flake.lock

echo "  Copying configuration.nix (substituting placeholders)"
sudo cp "$NIXOS_DIR/configuration.nix" /etc/nixos/configuration.nix

sudo sed -i "s/YOUR_USERNAME/$USERNAME/g" /etc/nixos/configuration.nix /etc/nixos/hosts/*.nix
sudo sed -i "s/YOUR_HOSTNAME/$HOSTNAME/g" /etc/nixos/configuration.nix
sudo sed -i "s|YOUR_TIMEZONE|$TIMEZONE|g"  /etc/nixos/configuration.nix

echo "  Done — /etc/nixos/:"
ls /etc/nixos/

# ---------------------------------------------------------------------------
# Dotfiles symlinks: before the rebuild, which needs network. Without them
# Hyprland writes its own default config, which does not start Caelestia
# ---------------------------------------------------------------------------
header "Creating dotfiles symlinks"
bash "$NIXOS_DIR/lib/link-dotfiles.sh"

# ---------------------------------------------------------------------------
# nixos-rebuild switch
# ---------------------------------------------------------------------------
header "Running nixos-rebuild switch (this will take a while on first run)"
# Lock first: adds inputs missing from flake.lock (never updates existing
# ones). A lock written mid-rebuild breaks the flake's hash
REBUILD_FAILED=""
REBUILD_LOG="$HOME/.cache/nixos-rebuild.log" # not /tmp: it must survive a reboot
mkdir -p "$(dirname "$REBUILD_LOG")"
if ! getent hosts github.com >/dev/null 2>&1 && ! getent hosts cache.nixos.org >/dev/null 2>&1; then
    echo "  WARNING: no network (github.com does not resolve): the rebuild will probably fail."
    echo "           Connect first (nmtui, or a cable), then run init.sh again."
fi
if sudo nix --extra-experimental-features "nix-command flakes" flake lock /etc/nixos &&
    sudo nixos-rebuild switch --impure --flake "/etc/nixos#$FLAKE_HOST" 2>&1 | tee "$REBUILD_LOG"; then
    # Keep the last 3 system generations; the weekly nix-gc frees their space
    sudo nix-env --profile /nix/var/nix/profiles/system --delete-generations +3 >/dev/null
else
    REBUILD_FAILED=1
    echo
    echo "  ERROR: nixos-rebuild failed (log: $REBUILD_LOG). Continuing with the rest;"
    echo "         the system stays as it was. Fix the cause, then run init.sh again."
fi

# Apply icon theme + dark mode via gsettings (required for GTK4/libadwaita apps)
header "Applying GTK icon theme and color scheme"
export XDG_DATA_DIRS="/run/current-system/sw/share:${XDG_DATA_DIRS:-/usr/local/share:/usr/share}"
gsettings set org.gnome.desktop.interface icon-theme  'Papirus-Dark'  2>/dev/null && echo "  icon-theme  → Papirus-Dark"   || echo "  gsettings unavailable (run after rebuild)"
gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark'  2>/dev/null && echo "  color-scheme → prefer-dark"    || true
gsettings set org.gnome.desktop.interface cursor-theme 'Adwaita' 2>/dev/null || true # = Hyprland's

# ---------------------------------------------------------------------------
# Home setup: Copilot off in Neovim, tmux plugin manager, Terraform completion
# (lib/home-setup.sh; the installer already ran it on a fresh install)
# ---------------------------------------------------------------------------
header "Home setup (Copilot flag, tmux plugins, zsh completions)"
bash "$NIXOS_DIR/lib/home-setup.sh"

# ---------------------------------------------------------------------------
# gh copilot extension
# ---------------------------------------------------------------------------
header "GitHub Copilot CLI"
if cmd_exists gh; then
    if ! gh extension list 2>/dev/null | grep -q 'gh-copilot'; then
        gh extension install github/gh-copilot || true
        echo "  gh copilot installed"
    else
        echo "  gh copilot already installed"
    fi
fi

# ---------------------------------------------------------------------------
# Default shell → zsh
# ---------------------------------------------------------------------------
header "Setting default shell to zsh"
ZSH_PATH="$(command -v zsh)"
if [[ "$SHELL" != "$ZSH_PATH" ]]; then
    if ! grep -q "$ZSH_PATH" /etc/shells; then
        echo "$ZSH_PATH" | sudo tee -a /etc/shells
    fi
    chsh -s "$ZSH_PATH" "$USERNAME"
    echo "  Default shell set to $ZSH_PATH"
else
    echo "  Already using zsh"
fi

# ---------------------------------------------------------------------------
# Neovim Python support
# ---------------------------------------------------------------------------
header "Neovim Python support"
if cmd_exists pip3; then
    pip3 install --user pynvim neovim 2>/dev/null || true
    echo "  pynvim installed"
else
    echo "  pip3 not found — skipping (pynvim is in system packages)"
fi

# ---------------------------------------------------------------------------
# Cliphist daemon (start for current session if not running)
# ---------------------------------------------------------------------------
header "Clipboard history daemon"
if ! pgrep -x cliphist &>/dev/null; then
    nohup wl-paste --watch cliphist store &>/dev/null &
    echo "  cliphist daemon started"
else
    echo "  cliphist already running"
fi

# ---------------------------------------------------------------------------
# Wallpaper reminder
# ---------------------------------------------------------------------------
echo
echo "┌─────────────────────────────────────────────────────────┐"
echo "│  Setup complete!                                        │"
echo "│                                                         │"
echo "│  Next steps:                                            │"
echo "│  1. Launch Hyprland:                                    │"
echo "│       Hyprland                                          │"
echo "│     (or reboot: the boot ends on Caelestia's lock)      │"
echo "│                                                         │"
echo "│  2. Inside Hyprland, open Neovim and run :Lazy sync     │"
echo "│                                                         │"
echo "│  Wallpapers: ~/Pictures/Wallpapers/                     │"
echo "│    default → quasar.webp                                │"
echo "└─────────────────────────────────────────────────────────┘"
echo
if [[ -n $REBUILD_FAILED ]]; then
    echo "  ERROR: nixos-rebuild failed: see $REBUILD_LOG"
    echo "         Everything else above is done. Run init.sh again once it is fixed."
    echo
    exit 1
fi
